/** 1〜99 を漢数字で書く（第十二歌、第三十二歌）。 */
export function jaKansuji(n:number):string{
 const d=['〇','一','二','三','四','五','六','七','八','九'];
 if(n<10)return d[n];
 const juu=Math.floor(n/10),ichi=n%10;
 return (juu>1?d[juu]:'')+'十'+(ichi?d[ichi]:'');
}
