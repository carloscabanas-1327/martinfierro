/** 把 1–99 写成中文数字（第十二歌、第三十二歌）。 */
export function zhShu(n:number):string{
 const d=['零','一','二','三','四','五','六','七','八','九'];
 if(n<10)return d[n];
 const shi=Math.floor(n/10),ge=n%10;
 return (shi>1?d[shi]:'')+'十'+(ge?d[ge]:'');
}
